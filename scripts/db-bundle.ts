/**
 * Bundle supabase/migrations/*.sql + supabase/seed.sql into a single
 * paste-ready file and print it to stdout. Pipe to pbcopy on macOS:
 *
 *   npx tsx scripts/db-bundle.ts | pbcopy
 *
 * Then paste into Supabase Dashboard → SQL Editor → Run.
 */
import fs from 'fs'
import path from 'path'

const root = path.resolve(process.cwd(), 'supabase')
const migrationsDir = path.join(root, 'migrations')
const seedPath = path.join(root, 'seed.sql')

const files = fs
  .readdirSync(migrationsDir)
  .filter((f) => f.endsWith('.sql'))
  .sort()

let out = `-- Generated by scripts/db-bundle.ts. Do not edit.\n-- Source: ${files.join(', ')} + seed.sql\n\n`

for (const f of files) {
  const body = fs.readFileSync(path.join(migrationsDir, f), 'utf-8')
  out += `\n-- ===== ${f} =====\n${body}\n`
}

if (fs.existsSync(seedPath)) {
  out += `\n-- ===== seed.sql =====\n${fs.readFileSync(seedPath, 'utf-8')}\n`
}

process.stdout.write(out)
